package org.ibrahim.tasktracker.service.impl;


import org.ibrahim.tasktracker.domain.CreateTaskRequest;
import org.ibrahim.tasktracker.domain.entity.Task;
import org.ibrahim.tasktracker.domain.entity.TaskStatus;
import org.ibrahim.tasktracker.repository.TaskRepository;
import org.ibrahim.tasktracker.service.TaskService;
import org.springframework.stereotype.Service;

import java.time.Instant;

@Service
public class TaskServiceImpl implements TaskService {

    private final TaskRepository taskRepository;

    public TaskServiceImpl(TaskRepository taskRepository) {
        this.taskRepository = taskRepository;
    }

    @Override
    public Task createTask(CreateTaskRequest request) {
        Instant now  = Instant.now();

        Task task = new Task(
                null, // Generated by hibernate
                request.title(),
                request.description(),
                request.dueDate(),
                TaskStatus.OPEN, // Default status
                request.priority(),
                now,
                now
        );

        return taskRepository.save(task);
    }
}
